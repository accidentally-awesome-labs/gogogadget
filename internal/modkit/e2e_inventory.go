package modkit

import (
	"context"
	"encoding/json"
	"fmt"
	"sort"
	"strings"
)

type playwrightInventoryEntry struct {
	Module        string   `json:"module"`
	E2E           []string `json:"e2e"`
	Visual        []string `json:"visual"`
	Accessibility []string `json:"accessibility"`
	Smoke         []string `json:"smoke"`
	Capabilities  []string `json:"capabilities"`
}

func emitPlaywrightInventory(_ context.Context, _ string, _ Lock, graph []Manifest) (*GeneratedFile, error) {
	entries := make([]playwrightInventoryEntry, 0)
	for _, module := range graph {
		tests := module.Tests
		if len(tests.E2E)+len(tests.Visual)+len(tests.Accessibility)+len(tests.Smoke)+len(tests.Capabilities) == 0 {
			continue
		}
		owned := make(map[string]struct{}, len(module.Files))
		for _, file := range module.Files {
			owned[file.Target] = struct{}{}
		}
		for _, spec := range tests.E2E {
			if !strings.HasPrefix(spec, "e2e/") || !strings.HasSuffix(spec, ".spec.ts") {
				return nil, fmt.Errorf("module %s tests.e2e entry %q must name an e2e spec", module.ID, spec)
			}
			if _, ok := owned[spec]; !ok {
				return nil, fmt.Errorf("module %s advertises tests.e2e %q without owning that spec", module.ID, spec)
			}
		}
		entries = append(entries, playwrightInventoryEntry{
			Module: module.ID, E2E: append([]string{}, tests.E2E...), Visual: append([]string{}, tests.Visual...),
			Accessibility: append([]string{}, tests.Accessibility...), Smoke: append([]string{}, tests.Smoke...),
			Capabilities: append([]string{}, tests.Capabilities...),
		})
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].Module < entries[j].Module })
	data, err := json.MarshalIndent(entries, "", "  ")
	if err != nil {
		return nil, err
	}
	content := "// Code generated by ggg sync; DO NOT EDIT.\nexport const moduleTests = " + string(data) + " as const;\n"
	return &GeneratedFile{Path: "e2e/generated/inventory.ts", Content: content}, nil
}

// emitE2EDatabase renders the derived per-environment database address for the
// Playwright harness. Node lives only under e2e/, so the harness cannot read
// the lock or call the derivation; a generated TypeScript module is how it
// reads generated data already (personas, surfaces, this inventory), which is
// why that is the seam here too.
//
// It replaces a literal localhost:5432 in playwright.config.ts. `ggg test e2e`
// brings the TEST stack up and that stack publishes 15432, so the harness was
// seeding and driving whatever answered on the development port instead — the
// operator's own Postgres on a machine that runs one.
//
// Typed Record rather than `as const`: an environment that publishes no local
// service is absent, and the harness must be able to ask for a key that may
// not be there and refuse, rather than fail to typecheck.
func emitE2EDatabase(_ context.Context, _ string, lock Lock, graph []Manifest) (*GeneratedFile, error) {
	values := map[string]string{}
	for _, environment := range composeEnvironments {
		derived, err := DerivedEnvironmentValues(lock, graph, environment)
		if err != nil {
			return nil, err
		}
		if dsn := derived["DATABASE_URL"]; dsn != "" {
			values[environment] = dsn
		}
	}
	data, err := json.MarshalIndent(values, "", "  ")
	if err != nil {
		return nil, err
	}
	content := "// Code generated by ggg sync; DO NOT EDIT.\n//\n" +
		"// The database address each environment's own stack publishes, derived from\n" +
		"// the selected database adapter and that environment's effective host port.\n" +
		"export const databaseURLs: Record<string, string> = " + string(data) + ";\n"
	return &GeneratedFile{Path: "e2e/generated/database.ts", Content: content}, nil
}
