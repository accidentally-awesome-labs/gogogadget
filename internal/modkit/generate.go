func emitOpenAPIRegistry(ctx context.Context, modulePath string, lock Lock, graph []Manifest) (*GeneratedFile, error) {
	var b strings.Builder
	b.WriteString("# Code generated by ggg sync; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "# index: %s\n", indexSHA(lock))
	b.WriteString("openapi: 3.1.0\n")
	b.WriteString("info:\n")
	b.WriteString("  title: GoGoGadget API\n")
	b.WriteString("paths:\n")
	for _, m := range orderedModules(lock, graph) {
		for _, r := range m.Runtime.Routes {
			if m.Kind != ModuleSystem && m.Kind != ModuleWorkflow {
				continue
			}
			fmt.Fprintf(&b, "  %s:\n", strings.ToLower(r.Pattern))
			b.WriteString("    get:\n")
			fmt.Fprintf(&b, "      operationId: %s\n", operationID(r))
		}
	}
	_ = ctx
	return &GeneratedFile{Path: "internal/api/openapi_registry_gen.yaml", Content: b.String()}, nil
}

func operationID(r RouteContribution) string {
	return strings.ReplaceAll(r.ID, ".", "_")
}

