// GeneratedFile is one deterministic registry-owned output emitted by the
// generator pipeline. Every path is tool-owned; authored modules never claim
// these targets.
type GeneratedFile struct {
	Path    string
	Content string
}

// genHeader is the shared DO-NOT-EDIT banner for generated Go files. The
// indexSHA ties the output to the exact gogogadget.lock.json it was rendered
// from, so drift is detectable.
func genHeader(modulePath string, lock Lock) string {
	var b strings.Builder
	b.WriteString("// Code generated by ggg sync; DO NOT EDIT.\n")
	b.WriteString("//\n")
	fmt.Fprintf(&b, "// index: %s\n", indexSHA(lock))
	fmt.Fprintf(&b, "// registry: %s\n", lock.RegistryCommit)
	b.WriteString("\n")
	_ = modulePath
	return b.String()
}

// indexSHA is the deterministic digest of the resolved module graph. It changes
// whenever any selected module's revision, contract, or set changes.
func indexSHA(lock Lock) string {
	h := sha256.New()
	for _, id := range lock.Order {
		h.Write([]byte(id))
		h.Write([]byte{0})
	}
	for _, m := range lock.Modules {
		fmt.Fprintf(h, "%s@%d#%d\x00", m.ID, m.Revision, m.Contract)
	}
	h.Write([]byte(lock.RegistryCommit))
	return hex.EncodeToString(h.Sum(nil))
}

// GenerateAll renders every registry-owned output for the resolved graph. It
// is a pure function of (modulePath, lock, graph): identical inputs always
// produce byte-identical outputs, and the file list is sorted by path.
func GenerateAll(ctx context.Context, modulePath string, lock Lock, graph []Manifest) ([]GeneratedFile, error) {
	emitters := []struct {
		name string
		fn   func(context.Context, string, Lock, []Manifest) (*GeneratedFile, error)
	}{
		{"bootstrap", emitBootstrapRegistry},
		{"testhost", emitTestHostRegistry},
		{"routes", emitRoutesRegistry},
		{"chrome", emitChromeRegistry},
		{"settings_nav", emitSettingsNavigationRegistry},
		{"shell_slots", emitShellSlotsRegistry},
		{"locales", emitLocalesRegistry},
		{"catalog_en", emitCatalogRegistry},
		{"catalog_es", emitCatalogRegistryES},
		{"openapi", emitOpenAPIRegistry},
		{"queries", emitQueriesRegistry},
		{"static", emitStaticRegistry},
		{"ui_components", emitUIComponentsRegistry},
		{"styles", emitStylesRegistry},
		{"content", emitContentRegistry},
		{"config", emitConfigRegistry},
		{"jobs", emitJobsRegistry},
	}
	files := make([]GeneratedFile, 0, len(emitters))
	for _, emitter := range emitters {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		file, err := emitter.fn(ctx, modulePath, lock, graph)
		if err != nil {
			return nil, fmt.Errorf("generate %s: %w", emitter.name, err)
		}
		if file != nil {
			if !isGeneratedOutput(file.Path) {
				return nil, fmt.Errorf("emitter %s produced non-generated path %s", emitter.name, file.Path)
			}
			files = append(files, *file)
		}
	}
	sort.Slice(files, func(i, j int) bool { return files[i].Path < files[j].Path })
	return files, nil
}

// goImportName returns the base package identifier for an import path.
func goImportName(pkg string) string {
	base := pkg
	if i := strings.LastIndex(pkg, "/"); i >= 0 {
		base = pkg[i+1:]
	}
	if i := strings.LastIndex(base, "-"); i >= 0 {
		base = base[:i]
	}
	return base
}

// goVar returns a deterministic Go variable name for a module ID.
func goVar(id string) string {
	name := strings.ReplaceAll(id, "/", "_")
	name = strings.ReplaceAll(name, "-", "_")
	return name + "Module"
}

func goString(s string) string {
	return fmt.Sprintf("%q", s)
}

// orderedModules returns the graph modules in lock topological order.
func orderedModules(lock Lock, graph []Manifest) []Manifest {
	byID := make(map[string]Manifest, len(graph))
	for _, m := range graph {
		byID[m.ID] = m
	}
	ordered := make([]Manifest, 0, len(lock.Order))
	for _, id := range lock.Order {
		if m, ok := byID[id]; ok {
			ordered = append(ordered, m)
		}
	}
	return ordered
}

// collectRootNeeds returns needs whose capability is not provided by any
// module in the graph; these are ambient values supplied by Options.
func collectRootNeeds(lock Lock, graph []Manifest) []RuntimeNeed {
	provided := make(map[string]bool)
	for _, m := range orderedModules(lock, graph) {
		if m.Runtime.System != nil {
			for _, p := range m.Runtime.System.Provides {
				provided[p.Capability] = true
			}
		}
	}
	seen := make(map[string]bool)
	needs := make([]RuntimeNeed, 0)
	for _, m := range orderedModules(lock, graph) {
		if m.Runtime.System == nil {
			continue
		}
		for _, n := range m.Runtime.System.Needs {
			if provided[n.Capability] || seen[n.Field] {
				continue
			}
			seen[n.Field] = true
			needs = append(needs, n)
		}
	}
	return needs
}

func isRootCapability(rootNeeds []RuntimeNeed, need RuntimeNeed) bool {
	for _, n := range rootNeeds {
		if n.Capability == need.Capability && n.Field == need.Field {
			return true
		}
	}
	return false
}

// emitBootstrapRegistry renders internal/modules/bootstrap_registry_gen.go,
// the only file that imports every selected system module. It generates direct
// constructor calls in topological order so an incorrect manifest declaration
// becomes a compile error on a named generated line.
func emitBootstrapRegistry(ctx context.Context, modulePath string, lock Lock, graph []Manifest) (*GeneratedFile, error) {
	modules := orderedModules(lock, graph)
	rootNeeds := collectRootNeeds(lock, graph)
	var b strings.Builder
	b.WriteString(genHeader(modulePath, lock))
	b.WriteString("package modules\n\n")
	b.WriteString("import (\n")
	b.WriteString("\t\"context\"\n")
	b.WriteString("\t\"fmt\"\n")
	b.WriteString("\t\"net/http\"\n")
	b.WriteString("\n")
	b.WriteString("\tapphost \"" + modulePath + "/internal/apphost\"\n")
	imports := make([]string, 0)
	for _, m := range modules {
		if m.Runtime.System != nil && m.Runtime.System.Package != "" {
			imports = append(imports, "\t"+goImportName(m.Runtime.System.Package)+" \""+m.Runtime.System.Package+"\"\n")
		}
	}
	sort.Strings(imports)
	for _, line := range imports {
		b.WriteString(line)
	}
	b.WriteString(")\n\n")

	b.WriteString("// Options carries the ambient values the selected closure boots with.\n")
	b.WriteString("type Options struct {\n")
	for _, need := range rootNeeds {
		fmt.Fprintf(&b, "\t%s %s\n", need.Field, need.Type)
	}
	b.WriteString("}\n\n")
	b.WriteString("// Runtime is the booted module closure.\n")
	b.WriteString("type Runtime struct {\n")
	b.WriteString("\thandler http.Handler\n")
	b.WriteString("\tstop    []apphost.Stop\n")
	b.WriteString("}\n\n")

	b.WriteString("// Boot validates the selected closure and constructs typed dependencies in\n")
	b.WriteString("// stable topological order, then starts long-lived services.\n")
	b.WriteString("func Boot(ctx context.Context, h apphost.Host, opts Options) (*Runtime, error) {\n")
	b.WriteString("\tr := &Runtime{}\n")
	b.WriteString("\t_ = h\n")
	provider := make(map[string]string)
	stoppers := make([]string, 0)
	for _, m := range modules {
		sys := m.Runtime.System
		if sys == nil || sys.Package == "" || sys.Constructor == "" {
			continue
		}
		if err := validateIdentifiers(sys); err != nil {
			return nil, fmt.Errorf("module %s: %w", m.ID, err)
		}
		pkg := goImportName(sys.Package)
		varName := goVar(m.ID)
		fmt.Fprintf(&b, "\t%s, err := %s.%s(ctx, h, %s.Deps{\n", varName, pkg, sys.Constructor, pkg)
		for _, need := range sys.Needs {
			if !validIdentifier(need.Field) {
				return nil, fmt.Errorf("module %s: invalid need field %q", m.ID, need.Field)
			}
			if expr, ok := provider[need.Capability]; ok {
				fmt.Fprintf(&b, "\t\t%s: %s,\n", need.Field, expr)
				continue
			}
			if isRootCapability(rootNeeds, need) {
				fmt.Fprintf(&b, "\t\t%s: opts.%s,\n", need.Field, need.Field)
				continue
			}
			if need.Optional {
				continue
			}
			return nil, fmt.Errorf("module %s: no module provides capability %q for need %s", m.ID, need.Capability, need.Field)
		}
		b.WriteString("\t})\n")
		b.WriteString("\tif err != nil {\n")
		fmt.Fprintf(&b, "\t\treturn nil, fmt.Errorf(\"boot %s: %%w\", err)\n", goString(m.ID)[1:len(goString(m.ID))-1])
		b.WriteString("\t}\n")
		for _, provide := range sys.Provides {
			if !validIdentifier(provide.Field) {
				return nil, fmt.Errorf("module %s: invalid provide field %q", m.ID, provide.Field)
			}
			provider[provide.Capability] = varName + "." + provide.Field
		}
		if sys.Stop {
			stoppers = append(stoppers, varName)
		}
	}
	b.WriteString("\t_ = r\n")
	b.WriteString("\treturn r, nil\n")
	b.WriteString("}\n\n")

	b.WriteString("// Handler returns the composed HTTP handler.\n")
	b.WriteString("func (r *Runtime) Handler() http.Handler { return r.handler }\n\n")
	b.WriteString("// Run starts long-lived services.\n")
	b.WriteString("func (r *Runtime) Run(ctx context.Context) error { return nil }\n\n")
	b.WriteString("// Close stops services in reverse dependency order.\n")
	b.WriteString("func (r *Runtime) Close(ctx context.Context) error {\n")
	for i := len(stoppers) - 1; i >= 0; i-- {
		fmt.Fprintf(&b, "\t_ = %s\n", stoppers[i])
	}
	b.WriteString("\treturn nil\n")
	b.WriteString("}\n")

	_ = ctx
	return &GeneratedFile{Path: "internal/modules/bootstrap_registry_gen.go", Content: b.String()}, nil
}

func validateIdentifiers(sys *SystemContribution) error {
	if !validPackagePath(sys.Package) {
		return fmt.Errorf("invalid system package path %q", sys.Package)
	}
	if !validIdentifier(sys.Constructor) {
		return fmt.Errorf("invalid system constructor %q", sys.Constructor)
	}
	return nil
}

// emitTestHostRegistry renders internal/modules/testhost_registry_gen.go. It
// exposes a TestHost used by tests to construct a runtime against a fixture
// lock; Boot never reads this table.
func emitTestHostRegistry(ctx context.Context, modulePath string, lock Lock, graph []Manifest) (*GeneratedFile, error) {
	modules := orderedModules(lock, graph)
	var b strings.Builder
	b.WriteString(genHeader(modulePath, lock))
	b.WriteString("package modules\n\n")
	b.WriteString("// testHostModules lists the module IDs a test runtime boots with. Boot never\n")
	b.WriteString("// reads this table; test-only items are addressable only here.\n")
	b.WriteString("var testHostModules = []string{\n")
	for _, m := range modules {
		fmt.Fprintf(&b, "\t%s,\n", goString(m.ID))
	}
	b.WriteString("}\n\n")
	b.WriteString("// TestHost returns the module IDs a test runtime boots with.\n")
	b.WriteString("func TestHost() []string { return append([]string{}, testHostModules...) }\n")
	_ = ctx
	return &GeneratedFile{Path: "internal/modules/testhost_registry_gen.go", Content: b.String()}, nil
}

// emitRoutesRegistry renders internal/web/routes_registry_gen.go from every
// selected RouteContribution, in module topological order then lexical ID.
func emitRoutesRegistry(ctx context.Context, modulePath string, lock Lock, graph []Manifest) (*GeneratedFile, error) {
	type route struct {
		moduleID string
		contrib  RouteContribution
	}
	routes := make([]route, 0)
	for _, m := range orderedModules(lock, graph) {
		for _, r := range m.Runtime.Routes {
			routes = append(routes, route{moduleID: m.ID, contrib: r})
		}
	}
	sort.Slice(routes, func(i, j int) bool {
		if routes[i].moduleID != routes[j].moduleID {
			return routes[i].moduleID < routes[j].moduleID
		}
		return routes[i].contrib.ID < routes[j].contrib.ID
	})

	var b strings.Builder
	b.WriteString(genHeader(modulePath, lock))
	b.WriteString("package web\n\n")
	b.WriteString("// RouteRegistry is the complete set of selected routes. The runtime content\n")
	b.WriteString("// loop is gone; every pattern is known before boot.\n")
	b.WriteString("var RouteRegistry = []Route{\n")
	for _, r := range routes {
		fmt.Fprintf(&b, "\t{ID: %s, Method: %s, Pattern: %s, Scope: %s,\n",
			goString(r.contrib.ID), goString(r.contrib.Method), goString(r.contrib.Pattern), goString(string(r.contrib.Scope)))
		fmt.Fprintf(&b, "\t\tPolicy: RoutePolicy{CSRFExempt: %t, CSRFReason: %s, RateExempt: %t, MaintenanceExempt: %t, MaxBodyBytes: %d, Idempotent: %t, AdminWrite: %t},\n",
			r.contrib.Policy.CSRFExempt, goString(r.contrib.Policy.CSRFReason),
			r.contrib.Policy.RateExempt, r.contrib.Policy.MaintenanceExempt,
			r.contrib.Policy.MaxBodyBytes, r.contrib.Policy.Idempotent, r.contrib.Policy.AdminWrite)
		fmt.Fprintf(&b, "\t\tHandler: (*Server).%sHandler, Enabled: (*Server).%sEnabled},\n",
			routeHandlerName(r.contrib), routeEnabledName(r.contrib))
	}
	b.WriteString("}\n")
	_ = ctx
	return &GeneratedFile{Path: "internal/web/routes_registry_gen.go", Content: b.String()}, nil
}

func routeHandlerName(r RouteContribution) string {
	if r.Handler == "" {
		return "noop"
	}
	return r.Handler
}

func routeEnabledName(r RouteContribution) string {
	if r.Enabled == "" {
		return "always"
	}
	return r.Enabled
}

